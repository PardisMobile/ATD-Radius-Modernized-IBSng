"""PostgreSQL acceptance tests for read-only A1.24 semantic inventory."""
from __future__ import annotations

import os
import uuid

import psycopg
from psycopg import sql
from psycopg.conninfo import make_conninfo
import pytest

from atd_radius.cli.a124_preflight import _target_inventory


@pytest.fixture
def isolated_inventory_schema():
    base_dsn = os.environ.get("ATD_TEST_DATABASE_URL")
    if not base_dsn:
        pytest.skip("ATD_TEST_DATABASE_URL is required for PostgreSQL inventory acceptance")
    schema = "atd_inventory_" + uuid.uuid4().hex[:12]
    with psycopg.connect(base_dsn) as conn:
        conn.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema)))
        conn.execute(sql.SQL(
            "CREATE TABLE {}.sample (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "name TEXT NOT NULL UNIQUE, parent_id BIGINT, "
            "CONSTRAINT sample_name_check CHECK (length(name) > 0), "
            "CONSTRAINT sample_parent_fk FOREIGN KEY (parent_id) REFERENCES {}.sample(id))"
        ).format(sql.Identifier(schema), sql.Identifier(schema)))
        conn.execute(sql.SQL("CREATE SEQUENCE {}.standalone_seq START 7 INCREMENT 3").format(sql.Identifier(schema)))
        conn.execute(sql.SQL("CREATE FUNCTION {}.sample_fn(integer) RETURNS integer "
                             "LANGUAGE SQL IMMUTABLE AS 'SELECT $1 + 1'").format(sql.Identifier(schema)))
        conn.execute(sql.SQL("CREATE FUNCTION {}.sample_trigger_fn() RETURNS trigger "
                             "LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$").format(sql.Identifier(schema)))
        conn.execute(sql.SQL("CREATE TRIGGER sample_touch BEFORE INSERT ON {}.sample "
                             "FOR EACH ROW EXECUTE FUNCTION {}.sample_trigger_fn()").format(
                                 sql.Identifier(schema), sql.Identifier(schema)))
        conn.commit()
    try:
        yield base_dsn, schema
    finally:
        with psycopg.connect(base_dsn) as conn:
            conn.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(sql.Identifier(schema)))
            conn.commit()


def test_target_inventory_reports_constraints_triggers_functions_and_sequence_state(isolated_inventory_schema):
    dsn, schema = isolated_inventory_schema
    with psycopg.connect(dsn) as conn:
        inventory = _target_inventory(conn, schema)

    constraints = {(item["table"], item["name"], item["type"]) for item in inventory["constraints"]}
    assert ("sample", "sample_pkey", "p") in constraints
    assert ("sample", "sample_name_key", "u") in constraints
    assert ("sample", "sample_name_check", "c") in constraints
    assert ("sample", "sample_parent_fk", "f") in constraints
    assert any(item["name"] == "sample_touch" and "sample_trigger_fn" in item["definition"]
               for item in inventory["triggers"])
    assert ("sample_fn", ("integer",)) in inventory["function_signatures"]
    assert any(item["name"] == "standalone_seq" and item["increment"] == 3
               for item in inventory["sequence_states"])
